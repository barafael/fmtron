#!/usr/bin/env python3
"""Copy the golden matrix into the static site and write the catalog index.

The matrix itself is generated by `tests/fmt_ron_matrix.rs` into
`test_data/fmt_ron_matrix/`. The matrix page is plain files under `www/`, so
this script keeps the copy there and derives `data/index.json` from it.

Run it from anywhere:

    python3 tools/build_matrix_site.py
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "test_data" / "fmt_ron_matrix"
DESTINATION = ROOT / "www" / "matrix" / "data"

# The matrix is serialized by serde with four-space indentation. Parsing the
# shape we generate is enough for the catalog; the rows are the source of the
# displayed settings and counts.
SETTINGS = re.compile(r"\n    settings: \((.*?)\n    \),", re.DOTALL)
CONFIGS = re.compile(r"\n    configs: \[(.*?)\n    \],", re.DOTALL)
QUOTED = re.compile(r'"((?:[^"\\]|\\.)*)"')
INPUT = re.compile(r'\n            input: "')
FAILED = re.compile(r"result: Failed\(")


def unescape(value: str) -> str:
    """Undo the RON string escapes that can appear in config names."""
    return json.loads(f'"{value}"')


def entry_for(path: Path) -> dict[str, object]:
    text = path.read_text(encoding="utf-8")
    settings = SETTINGS.search(text)
    configs = CONFIGS.search(text)
    if settings is None or configs is None:
        raise SystemExit(f"{path}: not a matrix row")
    names = [unescape(name) for name in QUOTED.findall(configs.group(1))]
    return {
        "id": path.stem,
        "file": path.name,
        "configs": names,
        "settings": settings.group(1),
        "inputs_count": len(INPUT.findall(text)),
        "failed_count": len(FAILED.findall(text)),
    }


def main() -> None:
    if not SOURCE.is_dir():
        raise SystemExit(f"{SOURCE}: missing; run the fmt_ron_matrix test first")

    DESTINATION.mkdir(parents=True, exist_ok=True)

    rows = sorted(SOURCE.glob("*.ron"))
    expected = {path.name for path in rows}
    for stale in DESTINATION.glob("*.ron"):
        if stale.name not in expected:
            stale.unlink()
    for path in rows:
        shutil.copyfile(path, DESTINATION / path.name)

    entries = [entry_for(path) for path in rows if path.name != "manifest.ron"]
    entries.sort(key=lambda entry: (entry["settings"], entry["id"]))
    index = {"entries": entries, "count": len(entries)}
    (DESTINATION / "index.json").write_text(
        json.dumps(index, separators=(",", ":")) + "\n", encoding="utf-8"
    )
    print(f"wrote {DESTINATION / 'index.json'} ({len(entries)} rows)")


if __name__ == "__main__":
    main()
